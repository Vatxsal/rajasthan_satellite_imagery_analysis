import type { SummaryLanguage } from "../../analysis/types";

/**
 * Static copy for the emailed change report (English + Hindi).
 * Every user-visible string in the template lives here so the route can
 * render either language without touching layout code.
 */
export interface ReportCopy {
  /** Hidden preheader shown after the subject in most clients (~90 chars). */
  preheader: (area: string, dateA: string, dateB: string) => string;
  doNotReply: string;
  autoGenerated: string;
  reportTitle: string;
  overviewHeading: string;
  levelLabel: Record<"district" | "tehsil" | "ilr", string>;
  datesLabel: string;
  gapLabel: (days: number) => string;
  sensitivityLabel: string;
  sensitivity: Record<"low" | "medium" | "high", string>;
  minPatchLabel: string;
  inputModeLabel: string;
  inputMode: Record<"single" | "composite", string>;
  /** Method & evidence one-liner (method-card parity, Phase 5). */
  methodLine: (parts: { rules: string; sar: string; prior: string; terrain: string }) => string;
  methodRules: Record<"legacy" | "fused" | "ml", string>;
  methodSar: (orbit: string, windowDays: number | null) => string;
  methodSarSkipped: (reason: string) => string;
  methodSarOff: string;
  methodPrior: string;
  methodPriorOff: string;
  methodTerrain: (instance: string) => string;
  methodTerrainOff: string;
  caveatHeading: string;
  caveats: {
    legacy: string;
    sarSkipped: (reason: string) => string;
    noPrior: string;
    noTerrain: string;
    confidenceNote: string;
  };
  glanceHeading: string;
  changedArea: string;
  shareOfValid: string;
  patchCount: string;
  validCoverage: string;
  classesHeading: string;
  colClass: string;
  colArea: string;
  colShare: string;
  shareOfChange: string;
  eventsHeading: string;
  eventsNote: string;
  colRank: string;
  colConfidence: string;
  colWhere: string;
  colCoords: string;
  colMap: string;
  confidence: Record<"high" | "medium" | "low", string>;
  confidenceUnknown: string;
  viewOnMap: string;
  noEvents: string;
  dash: string;
  tehsilsHeading: string;
  colTehsil: string;
  colChanged: string;
  summaryHeading: string;
  summaryDisclaimer: string;
  summarySections: {
    keyChanges: string;
    where: string;
    visual: string;
    reliability: string;
    next: string;
  };
  summaryUnavailable: string;
  imageCaption: string;
  cta: string;
  ctaNote: string;
  orCopyLink: string;
  howToReadHeading: string;
  howToRead: string;
  attribution: string;
  consentFooter: string;
  /** Fixed-recipient mode: names the site and the mailbox's alert role. */
  consentFooterFixed: (site: string) => string;
  /** Fixed-recipient mode: request time (IST) — no IP or visitor details. */
  requestedLine: (dateTime: string) => string;
  generatedOn: (date: string) => string;
}

